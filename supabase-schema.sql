-- ================================================================
-- CardioTrack - Configuración inicial de Supabase
-- Prototipo académico de monitoreo cardiaco remoto
-- Ejecutar una sola vez en Supabase > SQL Editor.
-- Los pacientes y registros incluidos son datos sintéticos.
-- ================================================================

begin;

create extension if not exists pgcrypto;

-- ------------------------------------------------
-- 1. Catálogos y datos clínicos seudonimizados
-- ------------------------------------------------

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default 'Usuario clínico',
  role text not null default 'clinician'
    check (role in ('clinician', 'analyst', 'admin')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.patients (
  id uuid primary key default gen_random_uuid(),
  patient_code text not null unique
    check (patient_code ~ '^CT-[0-9]{3}$'),
  age smallint check (age between 0 and 120),
  sex text check (sex in ('F', 'M', 'X', 'ND')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null
);

create table if not exists public.ecg_records (
  id bigint generated by default as identity primary key,
  patient_id uuid not null references public.patients(id) on delete restrict,
  recorded_at timestamptz not null default now(),
  heart_rate numeric(5,1) not null check (heart_rate between 20 and 250),
  signal_quality smallint not null check (signal_quality between 0 and 100),
  complexes_detected smallint check (complexes_detected >= 0),
  noise_level text not null default 'low'
    check (noise_level in ('low', 'medium', 'high')),
  status text not null
    check (status in ('stable', 'review', 'quality')),
  source text not null default 'SYNTHETIC_DEMO',
  algorithm_version text not null default 'ct-ecg-0.3.0',
  ecg_samples jsonb not null default '[]'::jsonb,
  clinical_note text,
  reviewed boolean not null default false,
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id) on delete set null,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint review_consistency check (
    (reviewed = false and reviewed_at is null and reviewed_by is null)
    or
    (reviewed = true and reviewed_at is not null)
  )
);

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_ecg_patient
  on public.ecg_records(patient_id);
create index if not exists idx_ecg_recorded_at
  on public.ecg_records(recorded_at desc);
create index if not exists idx_ecg_status
  on public.ecg_records(status, reviewed);
create index if not exists idx_audit_created_at
  on public.audit_log(created_at desc);

-- ------------------------------------------------
-- 2. Perfil automático al crear un usuario en Auth
-- ------------------------------------------------

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (user_id, full_name, role)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'full_name', ''), 'Usuario clínico'),
    'clinician'
  )
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ------------------------------------------------
-- 3. Datos sintéticos iniciales
-- ------------------------------------------------

insert into public.patients (patient_code, age, sex)
values
  ('CT-001', 62, 'F'),
  ('CT-002', 48, 'M'),
  ('CT-003', 35, 'F')
on conflict (patient_code) do update
set age = excluded.age,
    sex = excluded.sex;

insert into public.ecg_records
  (patient_id, recorded_at, heart_rate, signal_quality,
   complexes_detected, noise_level, status, source, algorithm_version)
select p.id, v.recorded_at, v.heart_rate, v.signal_quality,
       v.complexes_detected, v.noise_level, v.status,
       'SYNTHETIC_DEMO', 'ct-ecg-0.3.0'
from (
  values
    ('CT-002', '2026-11-19 14:28:00-06'::timestamptz, 118.1::numeric, 100::smallint, 19::smallint, 'low',  'review'),
    ('CT-003', '2026-11-19 11:28:00-06'::timestamptz,  46.0::numeric, 100::smallint,  8::smallint, 'low',  'review'),
    ('CT-001', '2026-11-19 08:28:00-06'::timestamptz, 157.9::numeric,  46::smallint, 26::smallint, 'high', 'quality'),
    ('CT-001', '2026-11-18 17:28:00-06'::timestamptz,  72.1::numeric, 100::smallint, 12::smallint, 'low',  'stable'),
    ('CT-002', '2026-11-18 05:28:00-06'::timestamptz,  78.1::numeric, 100::smallint, 13::smallint, 'low',  'stable')
) as v(patient_code, recorded_at, heart_rate, signal_quality,
       complexes_detected, noise_level, status)
join public.patients p on p.patient_code = v.patient_code
where not exists (
  select 1
  from public.ecg_records r
  where r.patient_id = p.id
    and r.recorded_at = v.recorded_at
);

-- ------------------------------------------------
-- 4. Bitácora automática de registros ECG
-- ------------------------------------------------

create or replace function public.audit_ecg_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.audit_log
    (user_id, action, entity_type, entity_id, details)
  values (
    auth.uid(),
    lower(tg_op),
    'ecg_record',
    new.id::text,
    jsonb_build_object(
      'patient_id', new.patient_id,
      'status', new.status,
      'reviewed', new.reviewed,
      'algorithm_version', new.algorithm_version
    )
  );
  return new;
end;
$$;

drop trigger if exists trg_audit_ecg_change on public.ecg_records;
create trigger trg_audit_ecg_change
  after insert or update on public.ecg_records
  for each row execute function public.audit_ecg_change();

-- ------------------------------------------------
-- 5. Seguridad: Row Level Security (RLS)
-- ------------------------------------------------

alter table public.profiles enable row level security;
alter table public.patients enable row level security;
alter table public.ecg_records enable row level security;
alter table public.audit_log enable row level security;

drop policy if exists "profile_read_own" on public.profiles;
create policy "profile_read_own"
  on public.profiles for select
  to authenticated
  using (user_id = auth.uid());

drop policy if exists "profile_update_own" on public.profiles;
create policy "profile_update_own"
  on public.profiles for update
  to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

drop policy if exists "patients_read_authenticated" on public.patients;
create policy "patients_read_authenticated"
  on public.patients for select
  to authenticated
  using (true);

drop policy if exists "patients_insert_authenticated" on public.patients;
create policy "patients_insert_authenticated"
  on public.patients for insert
  to authenticated
  with check (created_by is null or created_by = auth.uid());

drop policy if exists "patients_update_authenticated" on public.patients;
create policy "patients_update_authenticated"
  on public.patients for update
  to authenticated
  using (true)
  with check (true);

drop policy if exists "ecg_read_authenticated" on public.ecg_records;
create policy "ecg_read_authenticated"
  on public.ecg_records for select
  to authenticated
  using (true);

drop policy if exists "ecg_insert_authenticated" on public.ecg_records;
create policy "ecg_insert_authenticated"
  on public.ecg_records for insert
  to authenticated
  with check (created_by is null or created_by = auth.uid());

drop policy if exists "ecg_update_authenticated" on public.ecg_records;
create policy "ecg_update_authenticated"
  on public.ecg_records for update
  to authenticated
  using (true)
  with check (
    reviewed_by is null or reviewed_by = auth.uid()
  );

drop policy if exists "audit_read_authenticated" on public.audit_log;
create policy "audit_read_authenticated"
  on public.audit_log for select
  to authenticated
  using (true);

drop policy if exists "audit_insert_authenticated" on public.audit_log;
create policy "audit_insert_authenticated"
  on public.audit_log for insert
  to authenticated
  with check (user_id is null or user_id = auth.uid());

-- El visitante anónimo no puede consultar ni modificar información clínica.
revoke all on table public.profiles from anon;
revoke all on table public.patients from anon;
revoke all on table public.ecg_records from anon;
revoke all on table public.audit_log from anon;

grant select, update on table public.profiles to authenticated;
grant select, insert, update on table public.patients to authenticated;
grant select, insert, update on table public.ecg_records to authenticated;
grant select, insert on table public.audit_log to authenticated;
grant usage, select on all sequences in schema public to authenticated;

commit;

-- Resultado esperado: 3 pacientes y 5 registros sintéticos.
select
  (select count(*) from public.patients) as patients_created,
  (select count(*) from public.ecg_records) as records_created;
